import { execFileSync } from 'node:child_process'
import path from 'node:path'
import type { CalibratedSize, Peers } from '../../src/core/rosterGradeCalibration'
import { CALIBRATED_SIZES, MIN_PEERS } from '../../src/core/rosterGradeCalibrator'
import type { ReferenceTargetKey } from '../../src/core/rosterGrades'

const root = path.join(import.meta.dirname, '..', '..')
export const CALIBRATION_FILE = path.join(root, 'src', 'core', 'rosterGradeCalibration.ts')

/** The calibration table as `src/core/rosterGradeCalibration.ts` holds it, formatted as the repository formats it. */
export function calibrationSource(
  window: { since: string; until: string; drawn: string },
  expected: Record<CalibratedSize, readonly ReferenceTargetKey[]>,
  peers: Record<CalibratedSize, Record<string, Peers>>,
) {
  const list = (items: readonly (number | string)[]) => `[${items.map((value) => JSON.stringify(value)).join(', ')}]`
  const record = (entries: [string, string][]) => `{\n${entries.map(([key, value]) => `${key}: ${value},`).join('\n')}\n}`
  const sizes = <T>(value: (size: (typeof CALIBRATED_SIZES)[number]) => T, render: (value: T) => string) =>
    record(CALIBRATED_SIZES.map((size) => [String(size), render(value(size))]))
  const source = `/**
 * Roster grade percentiles from 11th-edition tournament lists (2,000 points, events in the \`CALIBRATED\` window)
 * that import cleanly; only these percentiles are kept. Each array holds a value at every fifth percentile, 0th
 * to 100th, as \`rosterGrades\` measures it, every value higher for a list that does the job better.
 *
 * Smaller battle sizes are drawn from the tournament lists' own units: of six random draws that fill most of the
 * points, the one with the most units, as a player fits as much as they can into a small game. Onslaught joins a
 * list with a 1,000-point draw from another list of its faction.
 *
 * Generated by \`scripts/calibrateRosterGrades.ts\`; rebuild it rather than editing it.
 */
import type { MetricKey, ReferenceTargetKey } from './rosterGrades'

/** The dates of the events the tournament lists come from, and the day they were measured. */
export const CALIBRATED = ${JSON.stringify(window)} as const

/** The battle sizes the tournament lists are drawn at; any other limit is compared with the nearest. */
export type CalibratedSize = ${CALIBRATED_SIZES.join(' | ')}

/** The targets at least nine in ten tournament lists of each size have a unit to take half of alone, so lacking one is worth naming. */
export const EXPECTED_TOOLS: Record<CalibratedSize, readonly ReferenceTargetKey[]> = ${sizes((size) => expected[size], list)}

export type Peers = {
  measures: Partial<Record<MetricKey, readonly number[]>>
  /** Each category's average measure percentile. */
  categories: Record<string, readonly number[]>
  /** The average category percentile. */
  overall: readonly number[]
}

/**
 * Tournament lists of one army and size, keyed by its catalogue's name or a parent of it, as
 * "Imperium - Adeptus Astartes", or of every army under ''. Only names with at least ${MIN_PEERS} tournament lists have
 * their own.
 */
export const PEERS: Record<CalibratedSize, Record<string, Peers>> = ${sizes(
    (size) => peers[size],
    (groups) =>
      record(
        Object.entries(groups).map(([key, group]) => [
          JSON.stringify(key),
          record([
            ['measures', record(Object.entries(group.measures).map(([metric, quantiles]) => [metric, list(quantiles)]))],
            ['categories', record(Object.entries(group.categories).map(([category, quantiles]) => [category, list(quantiles)]))],
            ['overall', list(group.overall)],
          ]),
        ]),
      ),
  )}
`
  return execFileSync(path.join(root, 'node_modules', '.bin', 'oxfmt'), [`--stdin-filepath=${CALIBRATION_FILE}`], {
    cwd: root,
    input: source,
    encoding: 'utf8',
  })
}
